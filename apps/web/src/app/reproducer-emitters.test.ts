// ── Byte-stability tests ─────────────────────────────────────────────────────

function testTypeScriptGoldenByteStable(): void {
  const model = buildReproducerModel(FIXTURE_BUNDLE);
  assert.equal(
    generateTSReproducerFromBundle(FIXTURE_BUNDLE),
    GOLDEN_TS,
    'TypeScript emitter golden must not change (byte-stable)',
  );
  assert.equal(
    generateTSReproducerFromBundle(FIXTURE_BUNDLE),
    generateTSReproducerFromBundle(FIXTURE_BUNDLE),
    'TypeScript emitter must be deterministic',
  );
  assert.ok(
    generateTSReproducerFromBundle(FIXTURE_BUNDLE).includes(String(model.seedId)),
    'model seedId should appear in TS output',
  );
  console.log('✓ testTypeScriptGoldenByteStable');
}

