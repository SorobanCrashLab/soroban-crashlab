function testMetadataBundleEmittersDeterministic(): void {
  const model = buildReproducerModel(FIXTURE_BUNDLE_WITH_METADATA);
  const rust = generateRustReproducer(model);
  const python = generatePythonReproducer(model);
  assert.ok(rust.includes('CAS3ODD6H6T4MWOTPGE4ZZGXWJZL4RBRVXHZCWXG7GJNUWQNIVPLJOTJ'), 'Rust should embed contract id');
  assert.ok(rust.includes('vec![0xca, 0xfe, 0xba, 0xbe]'), 'Rust should embed payload bytes');
  const rpcUrlLine = python.split('\n').find((line) => line.startsWith('RPC_URL = '));
  assert.strictEqual(
    rpcUrlLine,
    `RPC_URL = "${model.envFingerprint?.sorobanRpcUrl}"`,
    'Python should embed RPC url',
  );
  assert.ok(python.includes('0x01'), 'Python should embed invoke arg value');
  assert.equal(rust, generateRustReproducer(model), 'Rust emitter must be deterministic');
  assert.equal(python, generatePythonReproducer(model), 'Python emitter must be deterministic');
  console.log('✓ testMetadataBundleEmittersDeterministic');
}

// ── Invalid bundle tests ─────────────────────────────────────────────────────

function assertBundleError(bundle: unknown, messagePart: string, label: string): void {
  assert.throws(
    () => buildReproducerModel(bundle as CaseBundleExport),
    (err: unknown) => err instanceof Error && err.message.includes(messagePart),
    `${label} should throw a clean error mentioning "${messagePart}"`,
  );
  console.log(`✓ ${label}`);
}

function testInvalidBundlesThrowCleanErrors(): void {
  assertBundleError(null, 'expected an object', 'null bundle');
  assertBundleError({} as CaseBundleExport, 'seedId', 'missing seedId');
  assertBundleError(
    { seedId: 42, inputPayloadHex: 'zzzz', failureClass: 'x', signatureHash: '0x00', mode: 'invoker' } as CaseBundleExport,
    'inputPayloadHex',
    'non-hex payload',
  );
  assertBundleError(
    { seedId: 42, inputPayloadHex: 'deadbeef', failureClass: 'x', signatureHash: 'abc', mode: 'invoker' } as CaseBundleExport,
    'signatureHash',
    'odd-length signature hash',
  );
  assertBundleError(
    { seedId: -1, inputPayloadHex: 'deadbeef', failureClass: 'x', signatureHash: '0x00', mode: 'invoker' } as CaseBundleExport,
    'seedId',
    'negative seedId',
  );
  assertBundleError(
    { seedId: 42, inputPayloadHex: 'deadbeef', failureClass: 'x', signatureHash: '0x00', mode: 'invoker', invokeArgs: 'nope' } as unknown as CaseBundleExport,
    'invokeArgs',
    'non-array invokeArgs',
  );
}

