#!/usr/bin/env node
/**
 * Reproducibility evidence (#1898).
 *
 *   node scripts/reproducibility/evidence.mjs record --input probe.json --rustc "rustc 1.95.0" \
 *        --source <ci-run-url|local> --commit <sha> [--date YYYY-MM-DD]
 *   node scripts/reproducibility/evidence.mjs render     # rewrite the generated section
 *   node scripts/reproducibility/evidence.mjs check      # CI: section in sync + evidence fresh
 *   node scripts/reproducibility/evidence.mjs report <probe.json>...   # CI matrix summary
 *
 * Evidence lives in docs/reproducibility-evidence.json: one entry per
 * platform (os/arch), produced by `cargo run --release --example repro_probe`.
 * An entry passes when its digest equals the reference digest for the same
 * (engine, preset, seeds) — the contract says those must be identical
 * everywhere. The generated section of docs/reproducibility-contract.md is a
 * pure function of the evidence file, so `check` can prove it is in sync.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const EVIDENCE = path.join(ROOT, 'docs/reproducibility-evidence.json');
const DOC = path.join(ROOT, 'docs/reproducibility-contract.md');
const START = '<!-- reproducibility-evidence:start -->';
const END = '<!-- reproducibility-evidence:end -->';
export const MAX_AGE_DAYS = 45;

function arg(name) {
  const index = process.argv.indexOf(`--${name}`);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

function load() {
  return JSON.parse(fs.readFileSync(EVIDENCE, 'utf8'));
}

function key(entry) {
  return `${entry.engine}|${entry.preset}|${entry.seeds}`;
}

export function verdict(evidence, entry) {
  const reference = evidence.reference.find((ref) => key(ref) === key(entry));
  if (!reference) return 'no reference';
  if (entry.roundtripFailures > 0) return 'fail (bundle round trip)';
  return entry.digest === reference.digest ? 'pass' : 'fail (digest differs)';
}

export function render(evidence) {
  const lines = [
    START,
    '<!-- Generated by scripts/reproducibility/evidence.mjs render — do not edit by hand. -->',
    '',
    '| Platform | Engine | Preset / seeds | Toolchain | Digest | Result | Recorded | Source |',
    '|---|---|---|---|---|---|---|---|',
  ];
  const sorted = [...evidence.platforms].sort((a, b) => `${a.os}/${a.arch}`.localeCompare(`${b.os}/${b.arch}`));
  for (const entry of sorted) {
    const result = verdict(evidence, entry);
    const source = /^https?:/.test(entry.source) ? `[run](${entry.source})` : entry.source;
    lines.push(
      `| ${entry.os}/${entry.arch} | ${entry.engine} (bundle schema ${entry.bundleSchema}) | ${entry.preset} / ${entry.seeds} | ${entry.rustc} | \`${entry.digest}\` | ${result === 'pass' ? '✅ pass' : `❌ ${result}`} | ${entry.date} @ \`${entry.commit}\` | ${source} |`,
    );
  }
  lines.push('', `Reference digests: ${evidence.reference.map((r) => `\`${r.digest}\` (${r.engine}, ${r.preset}, ${r.seeds} seeds)`).join('; ')}.`, END);
  return lines.join('\n');
}

function writeSection(evidence) {
  const doc = fs.readFileSync(DOC, 'utf8');
  const start = doc.indexOf(START);
  const end = doc.indexOf(END);
  if (start < 0 || end < start) throw new Error(`${path.relative(ROOT, DOC)} has no generated-section markers`);
  fs.writeFileSync(DOC, doc.slice(0, start) + render(evidence) + doc.slice(end + END.length));
}

function check() {
  const evidence = load();
  const problems = [];
  const doc = fs.readFileSync(DOC, 'utf8');
  const current = doc.slice(doc.indexOf(START), doc.indexOf(END) + END.length);
  if (current !== render(evidence)) problems.push('generated section is out of date: run `node scripts/reproducibility/evidence.mjs render`');

  const now = Date.now();
  for (const entry of evidence.platforms) {
    const age = (now - Date.parse(`${entry.date}T00:00:00Z`)) / 86_400_000;
    if (age > MAX_AGE_DAYS) problems.push(`${entry.os}/${entry.arch} evidence is ${Math.floor(age)} days old (max ${MAX_AGE_DAYS}); re-run the probe and record it`);
    if (verdict(evidence, entry) === 'no reference') problems.push(`${entry.os}/${entry.arch}: no reference digest for ${key(entry)}`);
  }
  if (problems.length) {
    console.error(`${problems.length} reproducibility evidence problem(s):\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  const failing = evidence.platforms.filter((entry) => verdict(evidence, entry) !== 'pass');
  console.log(`reproducibility evidence OK: ${evidence.platforms.length} platform(s), ${failing.length} failing (reported in the doc), section in sync`);
}

function record() {
  const input = arg('input');
  if (!input) throw new Error('record needs --input probe.json');
  const probe = JSON.parse(fs.readFileSync(input, 'utf8'));
  const entry = {
    os: probe.os,
    arch: probe.arch,
    engine: probe.engine,
    bundleSchema: probe.bundleSchema,
    preset: probe.preset,
    seeds: probe.seeds,
    digest: probe.digest,
    roundtripFailures: probe.roundtripFailures,
    rustc: arg('rustc') ?? 'unknown',
    commit: arg('commit') ?? 'unknown',
    date: arg('date') ?? new Date().toISOString().slice(0, 10),
    source: arg('source') ?? 'local',
  };
  const evidence = load();
  evidence.platforms = evidence.platforms.filter((p) => !(p.os === entry.os && p.arch === entry.arch));
  evidence.platforms.push(entry);
  if (process.argv.includes('--reference')) {
    evidence.reference = evidence.reference.filter((r) => key(r) !== key(entry));
    evidence.reference.push({ engine: entry.engine, preset: entry.preset, seeds: entry.seeds, digest: entry.digest });
  }
  fs.writeFileSync(EVIDENCE, `${JSON.stringify(evidence, null, 2)}\n`);
  writeSection(evidence);
  console.log(`recorded ${entry.os}/${entry.arch}: ${verdict(evidence, entry)}`);
}

/** Summarises a CI matrix run (report-only): one line per probe file. */
function report(files) {
  const evidence = load();
  const rows = files.map((file) => {
    const probe = JSON.parse(fs.readFileSync(file, 'utf8'));
    return `| ${probe.os}/${probe.arch} | \`${probe.digest}\` | ${verdict(evidence, probe)} |`;
  });
  const out = ['| Platform | Digest | Result vs reference |', '|---|---|---|', ...rows].join('\n');
  console.log(out);
  return rows.every((row) => row.endsWith('| pass |'));
}

const command = process.argv[2];
if (command === 'render') {
  writeSection(load());
} else if (command === 'check') {
  check();
} else if (command === 'record') {
  record();
} else if (command === 'report') {
  report(process.argv.slice(3));
} else if (command) {
  console.error('usage: evidence.mjs record|render|check|report');
  process.exit(2);
}
